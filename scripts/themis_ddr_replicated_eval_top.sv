`timescale 1ns/1ps

module themis_ddr_replicated_eval_top #(
  parameter int CORES = 1,
  parameter int RANK_WIDTH = 6,
  parameter int SEQ_WIDTH = 16,
  parameter int AXI_ADDR_WIDTH = 64,
  parameter int AXI_DATA_WIDTH = 512,
  parameter int AXI_ID_WIDTH = 4,
  parameter int SRAM_DEPTH = 8,
  parameter int DDR_BATCH_SIZE = 8,
  parameter int DDR_BATCH_SLOTS = 8,
  parameter int BBQ_BITMAP_WIDTH = 8,
  parameter int SWAP_IN_WATERMARK = 2,
  parameter int SWAP_OUT_WATERMARK = 6,
  localparam int PAYLOAD_WIDTH = AXI_DATA_WIDTH - RANK_WIDTH - SEQ_WIDTH,
  localparam int AXI_KEEP_WIDTH = AXI_DATA_WIDTH / 8
) (
  input  logic                                      clk,
  input  logic                                      resetn,
  input  logic [CORES-1:0]                         enable,
  input  logic [CORES-1:0]                         flush,
  input  logic [CORES-1:0]                         dequeue_enable,

  input  logic [CORES-1:0]                         s_pkt_valid,
  output logic [CORES-1:0]                         s_pkt_ready,
  input  logic [CORES*RANK_WIDTH-1:0]              s_pkt_rank,
  input  logic [CORES*SEQ_WIDTH-1:0]               s_pkt_seq,
  input  logic [CORES*PAYLOAD_WIDTH-1:0]           s_pkt_payload,

  output logic [CORES-1:0]                         m_pkt_valid,
  input  logic [CORES-1:0]                         m_pkt_ready,
  output logic [CORES*RANK_WIDTH-1:0]              m_pkt_rank,
  output logic [CORES*SEQ_WIDTH-1:0]               m_pkt_seq,
  output logic [CORES*PAYLOAD_WIDTH-1:0]           m_pkt_payload,

  output logic [CORES*AXI_ID_WIDTH-1:0]            m_axi_awid,
  output logic [CORES*AXI_ADDR_WIDTH-1:0]          m_axi_awaddr,
  output logic [CORES*8-1:0]                       m_axi_awlen,
  output logic [CORES*3-1:0]                       m_axi_awsize,
  output logic [CORES*2-1:0]                       m_axi_awburst,
  output logic [CORES-1:0]                         m_axi_awlock,
  output logic [CORES*4-1:0]                       m_axi_awcache,
  output logic [CORES*3-1:0]                       m_axi_awprot,
  output logic [CORES*4-1:0]                       m_axi_awqos,
  output logic [CORES-1:0]                         m_axi_awvalid,
  input  logic [CORES-1:0]                         m_axi_awready,
  output logic [CORES*AXI_DATA_WIDTH-1:0]          m_axi_wdata,
  output logic [CORES*AXI_KEEP_WIDTH-1:0]          m_axi_wstrb,
  output logic [CORES-1:0]                         m_axi_wlast,
  output logic [CORES-1:0]                         m_axi_wvalid,
  input  logic [CORES-1:0]                         m_axi_wready,
  input  logic [CORES*AXI_ID_WIDTH-1:0]            m_axi_bid,
  input  logic [CORES*2-1:0]                       m_axi_bresp,
  input  logic [CORES-1:0]                         m_axi_bvalid,
  output logic [CORES-1:0]                         m_axi_bready,
  output logic [CORES*AXI_ID_WIDTH-1:0]            m_axi_arid,
  output logic [CORES*AXI_ADDR_WIDTH-1:0]          m_axi_araddr,
  output logic [CORES*8-1:0]                       m_axi_arlen,
  output logic [CORES*3-1:0]                       m_axi_arsize,
  output logic [CORES*2-1:0]                       m_axi_arburst,
  output logic [CORES-1:0]                         m_axi_arlock,
  output logic [CORES*4-1:0]                       m_axi_arcache,
  output logic [CORES*3-1:0]                       m_axi_arprot,
  output logic [CORES*4-1:0]                       m_axi_arqos,
  output logic [CORES-1:0]                         m_axi_arvalid,
  input  logic [CORES-1:0]                         m_axi_arready,
  input  logic [CORES*AXI_ID_WIDTH-1:0]            m_axi_rid,
  input  logic [CORES*AXI_DATA_WIDTH-1:0]          m_axi_rdata,
  input  logic [CORES*2-1:0]                       m_axi_rresp,
  input  logic [CORES-1:0]                         m_axi_rlast,
  input  logic [CORES-1:0]                         m_axi_rvalid,
  output logic [CORES-1:0]                         m_axi_rready
);

  genvar g;
  generate
    for (g = 0; g < CORES; g = g + 1) begin : gen_themis_ddr_core
      themis_core_stripped_top #(
        .RANK_WIDTH(RANK_WIDTH),
        .SEQ_WIDTH(SEQ_WIDTH),
        .AXI_ADDR_WIDTH(AXI_ADDR_WIDTH),
        .AXI_DATA_WIDTH(AXI_DATA_WIDTH),
        .AXI_ID_WIDTH(AXI_ID_WIDTH),
        .SRAM_DEPTH(SRAM_DEPTH),
        .DDR_BATCH_SIZE(DDR_BATCH_SIZE),
        .DDR_BATCH_SLOTS(DDR_BATCH_SLOTS),
        .BBQ_BITMAP_WIDTH(BBQ_BITMAP_WIDTH),
        .SWAP_IN_WATERMARK(SWAP_IN_WATERMARK),
        .SWAP_OUT_WATERMARK(SWAP_OUT_WATERMARK)
      ) core_i (
        .clk(clk),
        .resetn(resetn),
        .enable(enable[g]),
        .flush(flush[g]),
        .dequeue_enable(dequeue_enable[g]),
        .s_pkt_valid(s_pkt_valid[g]),
        .s_pkt_ready(s_pkt_ready[g]),
        .s_pkt_rank(s_pkt_rank[g*RANK_WIDTH +: RANK_WIDTH]),
        .s_pkt_seq(s_pkt_seq[g*SEQ_WIDTH +: SEQ_WIDTH]),
        .s_pkt_payload(s_pkt_payload[g*PAYLOAD_WIDTH +: PAYLOAD_WIDTH]),
        .m_pkt_valid(m_pkt_valid[g]),
        .m_pkt_ready(m_pkt_ready[g]),
        .m_pkt_rank(m_pkt_rank[g*RANK_WIDTH +: RANK_WIDTH]),
        .m_pkt_seq(m_pkt_seq[g*SEQ_WIDTH +: SEQ_WIDTH]),
        .m_pkt_payload(m_pkt_payload[g*PAYLOAD_WIDTH +: PAYLOAD_WIDTH]),
        .m_axi_awid(m_axi_awid[g*AXI_ID_WIDTH +: AXI_ID_WIDTH]),
        .m_axi_awaddr(m_axi_awaddr[g*AXI_ADDR_WIDTH +: AXI_ADDR_WIDTH]),
        .m_axi_awlen(m_axi_awlen[g*8 +: 8]),
        .m_axi_awsize(m_axi_awsize[g*3 +: 3]),
        .m_axi_awburst(m_axi_awburst[g*2 +: 2]),
        .m_axi_awlock(m_axi_awlock[g]),
        .m_axi_awcache(m_axi_awcache[g*4 +: 4]),
        .m_axi_awprot(m_axi_awprot[g*3 +: 3]),
        .m_axi_awqos(m_axi_awqos[g*4 +: 4]),
        .m_axi_awvalid(m_axi_awvalid[g]),
        .m_axi_awready(m_axi_awready[g]),
        .m_axi_wdata(m_axi_wdata[g*AXI_DATA_WIDTH +: AXI_DATA_WIDTH]),
        .m_axi_wstrb(m_axi_wstrb[g*AXI_KEEP_WIDTH +: AXI_KEEP_WIDTH]),
        .m_axi_wlast(m_axi_wlast[g]),
        .m_axi_wvalid(m_axi_wvalid[g]),
        .m_axi_wready(m_axi_wready[g]),
        .m_axi_bid(m_axi_bid[g*AXI_ID_WIDTH +: AXI_ID_WIDTH]),
        .m_axi_bresp(m_axi_bresp[g*2 +: 2]),
        .m_axi_bvalid(m_axi_bvalid[g]),
        .m_axi_bready(m_axi_bready[g]),
        .m_axi_arid(m_axi_arid[g*AXI_ID_WIDTH +: AXI_ID_WIDTH]),
        .m_axi_araddr(m_axi_araddr[g*AXI_ADDR_WIDTH +: AXI_ADDR_WIDTH]),
        .m_axi_arlen(m_axi_arlen[g*8 +: 8]),
        .m_axi_arsize(m_axi_arsize[g*3 +: 3]),
        .m_axi_arburst(m_axi_arburst[g*2 +: 2]),
        .m_axi_arlock(m_axi_arlock[g]),
        .m_axi_arcache(m_axi_arcache[g*4 +: 4]),
        .m_axi_arprot(m_axi_arprot[g*3 +: 3]),
        .m_axi_arqos(m_axi_arqos[g*4 +: 4]),
        .m_axi_arvalid(m_axi_arvalid[g]),
        .m_axi_arready(m_axi_arready[g]),
        .m_axi_rid(m_axi_rid[g*AXI_ID_WIDTH +: AXI_ID_WIDTH]),
        .m_axi_rdata(m_axi_rdata[g*AXI_DATA_WIDTH +: AXI_DATA_WIDTH]),
        .m_axi_rresp(m_axi_rresp[g*2 +: 2]),
        .m_axi_rlast(m_axi_rlast[g]),
        .m_axi_rvalid(m_axi_rvalid[g]),
        .m_axi_rready(m_axi_rready[g])
      );
    end
  endgenerate

endmodule
